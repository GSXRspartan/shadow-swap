#!/usr/bin/env node
// Render Shadow Swap's response-header policy for a self-hosted static origin, from the SAME
// source Cloudflare Pages uses (apps/web/src/lib/deploymentHeaders.ts), so a VPS deployment can
// never drift from the audited policy.
//
//   pnpm --filter @tari-ootle/web run build:test
//   node deploy/vps/render-static-headers.mjs nginx  > /etc/nginx/snippets/shadow-swap-headers.conf
//   node deploy/vps/render-static-headers.mjs caddy  > /etc/caddy/shadow-swap-headers.caddy
//
// Writes to stdout only. It never touches a server.
import { createRequire } from 'node:module';
import { existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const compiled = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'apps', 'web', 'build-test', 'lib', 'deploymentHeaders.js');
if (!existsSync(compiled)) {
  console.error('Run "pnpm --filter @tari-ootle/web run build:test" first.');
  process.exit(2);
}
const { SECURITY_HEADERS } = createRequire(import.meta.url)(compiled);
const format = process.argv[2];
const quote = (v) => `"${v.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

if (format === 'nginx') {
  console.log('# Generated by deploy/vps/render-static-headers.mjs. Do not edit by hand.');
  console.log('# `always` so the policy is also sent on 4xx/5xx responses.');
  for (const h of SECURITY_HEADERS) console.log(`add_header ${h.name} ${quote(h.value)} always;`);
} else if (format === 'caddy') {
  console.log('# Generated by deploy/vps/render-static-headers.mjs. Do not edit by hand.');
  console.log('header {');
  for (const h of SECURITY_HEADERS) console.log(`\t${h.name} ${quote(h.value)}`);
  console.log('\t-Server');
  console.log('\t-X-Frame-Options');
  console.log('}');
} else {
  console.error('usage: render-static-headers.mjs nginx|caddy');
  process.exit(2);
}
